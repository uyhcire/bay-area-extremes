#!/usr/bin/env python3
"""Render year-by-year tables (Version A, Version B, reconciliation to NHEA, checks) to docs/tables.md.  $ billions."""
import os
import pandas as pd
import hi_lib as L

a = pd.read_csv(os.path.join(L.OUT, "income_side_health_account.csv"), index_col=0)
ind = pd.read_csv(os.path.join(L.OUT, "independence_check.csv"), index_col=0)
uc = pd.read_csv(os.path.join(L.OUT, "user_cost_variant.csv"), index_col=0)
lev = pd.read_csv(os.path.join(L.OUT, "comparison_levels.csv"), index_col=0)
gr = pd.read_csv(os.path.join(L.OUT, "comparison_growth.csv"), index_col=0)
vol = pd.read_csv(os.path.join(L.OUT, "volatility_summary.csv"), index_col=[0, 1])

def md(df, fmt="{:,.1f}"):
    out = ["| year | " + " | ".join(df.columns) + " |", "|---|" + "---:|" * len(df.columns)]
    for y, r in df.iterrows():
        out.append(f"| {y} | " + " | ".join("n/a" if pd.isna(v) else (fmt.format(v) if not isinstance(v, str) else v) for v in r) + " |")
    return "\n".join(out)

b = a / 1e3
S = []
S.append("# Year-by-year tables\n\nGenerated by `code/40_make_tables.py` from `data/output/*.csv`. $ billions, current dollars, unless noted. "
         "`n/a` = not available (2025: CMS has not published NHEA 2025, so only the provider block exists). "
         "Tags: OBS = independently observed; PUB = published but derived by the agency (residual or expenditure-based); "
         "EST = estimated here; ASM = assumption with a range. See `methods.md`.\n")

t = pd.DataFrame({
    "Employee comp (OBS)": b["prov_comp"], "Proprietor labor, imputed (ASM)": b["prov_prop_labor"],
    "Capital income: GOS less proprietor labor (PUB/EST)": b["prov_gos"] - b["prov_prop_labor"],
    "Nonprofit+gov hospital surplus (OBS)": b["hosp_surplus_addon"],
    "Taxes less subsidies (PUB)": b["prov_topi"],
    "Intermediate: energy": b["prov_ii_energy"], "materials": b["prov_ii_materials"], "purchased services": b["prov_ii_services"],
    "less intra-provider sales (EST)": -b["prov_intra_sales"],
    "= Provider final output": b["prov_final_output"]})
S.append("## A1. Version A - provider block (income side)\n\nProviders = NAICS 621, 622, in-scope 623, in-scope 62412, state/local government "
         "hospitals and health, federal direct providers. Gross output = compensation + gross operating surplus + taxes + intermediate inputs; "
         "the hospital surplus is added because BEA values nonprofit and government output at cost.\n\n" + md(t))

t = pd.DataFrame({
    "Provider final output": b["prov_final_output"], "Retail Rx": b["np.retail_rx_drugs"], "Other non-durables": b["np.other_nondurable_products"],
    "DME": b["np.durable_medical_equipment"], "Net cost of insurance": b["np.net_cost_health_insurance"],
    "Gov admin": b["np.gov_admin_federal"] + b["np.gov_admin_state_local"], "Federal public health": b["np.public_health_federal"],
    "Research": b["np.research"], "Structures": b["np.structures"], "Equipment": b["np.equipment"],
    "= Income-side total A": b["A_total"], "low": b["A_total_low"], "high": b["A_total_high"],
    "NHE (CMS)": b["nhe_total"], "Discrepancy": b["discrepancy"]})
S.append("## A2. Version A - total\n\nNon-provider columns are CMS NHEA expenditure estimates (PUB, not independently observed); the discrepancy "
         "therefore arises entirely in the provider block. Low/high = assumption scenarios.\n\n" + md(t))

t = pd.DataFrame({
    "Labor: provider employees": b["B_labor_direct_employee"], "provider proprietors (ASM)": b["B_labor_direct_proprietor_imputed"],
    "suppliers to providers": b["B_labor_upstream_provider_inputs"], "drug/device/insurer/gov/investment chains": b["B_labor_nonprovider_chains"],
    "= Domestic labor": b["B_labor"],
    "Capital: providers": b["B_capital_direct"], "hospital surplus": b["B_capital_hospital_surplus"],
    "suppliers to providers ": b["B_capital_upstream_provider_inputs"], "other chains": b["B_capital_nonprovider_chains"],
    "= Domestic capital income": b["B_capital"], "Taxes less subsidies": b["B_taxes"], "Imports": b["B_imports"],
    "= Total B": b["B_total"]})
S.append("## B1. Version B - rolled up through input-output tables\n\nIntermediate inputs and non-provider purchases are traced to the "
         "compensation, gross operating surplus and taxes of supplying industries (BEA summary I-O tables; 2024 uses 2023 coefficients - EST). "
         "Imports are valued at the border and not traced abroad. Total B equals total A by construction.\n\n" + md(t))
sh = 100 * a[["B_labor", "B_capital", "B_taxes", "B_imports"]].div(a["B_total"], axis=0)
sh.columns = ["Labor %", "Capital income %", "Taxes %", "Imports %"]
sh["Labor %, low-high"] = [("n/a" if pd.isna(x) else f"{100*x/tt:.1f}-{100*y/tt:.1f}") for x, y, tt in zip(a["B_labor_low"], a["B_labor_high"], a["B_total"])]
S.append("## B2. Version B - shares of total\n\n" + md(sh))

t = pd.DataFrame({
    "NHE provider services (7 categories)": b["nhe_provider_services"], "+ S&L public health": b["nhe_public_health_state_local"],
    "= NHE provider boundary": b["nhe_provider_boundary"], "Income-side provider output": b["prov_final_output"],
    "Discrepancy": b["discrepancy"], "% of NHE": a["discrepancy_pct_nhe"], "% low": a["discrepancy_pct_nhe_low"], "% high": a["discrepancy_pct_nhe_high"],
    "Memo: NHE 'other federal programs' in provider services": b["memo_nhe_other_federal_programs_in_provider_services"],
    "Discrepancy excl. memo": b["discrepancy_ex_other_federal_programs"], "% of NHE ": a["discrepancy_ex_other_federal_programs_pct_nhe"],
    "Hospital surplus is estimate?": a["hosp_surplus_is_estimate"].map({True: "yes", False: "no"})})
S.append("## R1. Reconciliation to NHEA and statistical discrepancy\n\nDiscrepancy = NHE - income-side total = NHE provider boundary - income-side "
         "provider output. '% low/high' are the discrepancy under the high/low income-side scenarios. The memo column is spending CMS attributes "
         "to 'Other Federal Programs' inside the seven provider categories (Provider Relief Fund and PPP in 2020-23); BEA records those as "
         "subsidies, not output.\n\n" + md(t, "{:,.1f}"))

sec = ["ambulatory_621", "hospitals_private_622", "nursing_residential_623_scoped", "home_community_62412_scoped",
       "state_local_gov_hospitals_health", "federal_direct_providers"]
t = pd.DataFrame({s_.replace("_", " ") + " GO": b[s_ + ".go"] for s_ in sec})
S.append("## R2. Provider gross output by sector (in scope)\n\n621 and 622: BEA (PUB). 623 and 62412: BEA output x QCEW payroll scope shares (EST; "
         "62412 also x inclusion share, ASM). State/local: BEA (PUB). Federal: QCEW federal payroll x ratios (EST/ASM).\n\n" + md(t))

t = pd.DataFrame({
    "BEA comp 621-623": ind["bea_comp_621_623"] / 1e3, "QCEW private wages 621-623 (OBS)": ind["qcew_private_wages_621_623"] / 1e3,
    "ratio": ind["bea_comp_over_qcew_wages"],
    "BEA GOS, NAICS 62 (residual)": ind["bea_gos_62_residual"] / 1e3,
    "Corp profits before tax": ind["corp_profits_before_tax_62"] / 1e3, "Corp CCA": ind["corp_capital_consumption_allow_62"] / 1e3,
    "Proprietors' income": ind["proprietors_income_62"] / 1e3, "Noncorp CCA": ind["noncorp_capital_consumption_allow_62"] / 1e3,
    "Net interest (EST alloc.)": ind["net_interest_62_allocated"] / 1e3, "Nonprofit hospital depreciation (HCRIS)": ind["hcris_nonprofit_hosp_depreciation"] / 1e3,
    "= Independent sum": ind["capital_income_independent_sum"] / 1e3, "BEA GOS minus independent": ind["gap_bea_gos_minus_independent"] / 1e3,
    "gap % of VA": ind["gap_pct_of_va_62"]})
S.append("## I1. Independence check - private NAICS 62 (621-624)\n\nBEA's industry gross operating surplus is a residual (output - intermediate "
         "inputs - compensation - taxes). The independent sum is built from tax-return-based NIPA tables 6.12D, 6.13D, 6.15D, 6.17D, 6.22D and "
         "Medicare cost reports. HCRIS depreciation is missing 2002-04 (worksheet not in the files), so the sum is blank there.\n\n" + md(t, "{:,.2f}"))

t = pd.DataFrame({"HCRIS all-hospital total revenue": ind["hcris_all_hosp_total_revenue"] / 1e3, "NHE hospital care": ind["nhe_hospital_care"] / 1e3,
                  "HCRIS net income (all)": ind["hcris_all_hosp_net_income"] / 1e3, "HCRIS hospital-years": ind["hcris_all_hosp_report_years"]})
S.append("## I2. Hospital cross-check: Medicare cost reports vs NHE hospital care\n\nHCRIS excludes VA/DoD hospitals and is incomplete for 2025.\n\n" + md(t))

t = pd.DataFrame({"Net stock (current cost)": uc["net_stock_private_providers"] / 1e3, "Depreciation": uc["depreciation_private_providers"] / 1e3,
                  "Observed capital income": uc["observed_capital_income_private"] / 1e3,
                  "Capital services, r=5%": uc["capital_services_central"] / 1e3,
                  "Residual, r=5%": uc["residual_central"] / 1e3, "Residual, r=7%": uc["residual_high"] / 1e3, "Residual, r=3%": uc["residual_low"] / 1e3,
                  "Residual (r=5%) % of total A": uc["residual_central_pct_of_A_total"]})
S.append("## U1. User-cost variant (private provider industries)\n\nCapital services = BEA current-cost depreciation + real required return x "
         "average net stock of fixed assets (BEA Fixed Assets, in-scope 621-624). Observed capital income = GOS less imputed proprietor labor "
         "plus hospital surplus. The residual is observed minus imputed: returns above (or below) the required return, plus land, inventories, "
         "intangibles not capitalised, and measurement error. The real return is an assumption (ASM): 3%, 5%, 7%.\n\n" + md(t))

t = lev[["nhe_total", "income_side_total_A", "nhe_hce", "income_side_hce_basis", "nhe_phc", "pce_health_care_services"]] / 1e3
t.columns = ["NHE", "Income-side total", "NHE health consumption", "Income-side, consumption basis", "NHE personal health care", "PCE health care services"]
t["NHE % GDP"] = lev["nhe_share_gdp_pct"]; t["Income-side % GDP"] = lev["income_side_share_gdp_pct"]
t["NHE per capita $"] = lev["nhe_per_capita_usd"]; t["Income-side per capita $"] = lev["income_side_per_capita_usd"]
t["KFF family premium $"] = lev["kff_family_premium_usd"]; t["CPI medical"] = lev["cpi_medical_care"]; t["PCE health price idx"] = lev["pce_health_care_price_index"]
S.append("## C1. Comparison levels\n\n" + md(t))
g = gr[["nhe_total", "income_side_total_A", "nhe_provider_boundary", "income_side_provider_output", "provider_compensation_observed",
        "domestic_capital_B", "pce_health_care_services", "kff_family_premium_usd", "cpi_medical_care", "gdp"]]
g.columns = ["NHE", "Income-side total", "NHE provider boundary", "Income-side provider output", "Provider compensation",
             "Domestic capital income (B)", "PCE health services", "KFF family premium", "CPI medical", "GDP"]
S.append("## C2. Annual growth, %\n\n" + md(g.loc[1999:]))
v = vol.loc["2000-2024 common window"][["mean_growth_pct", "sd_growth_pct", "sd_change_in_growth_pp", "g2008", "g2009", "g2020", "g2021", "g2022"]]
v2 = vol.loc["2000-2019 pre-COVID"][["mean_growth_pct", "sd_growth_pct"]]; v2.columns = ["mean 2000-19", "sd 2000-19"]
v = v.join(v2); v.index.name = "series"
S.append("## C3. Volatility summary (growth rates, %; common window 2000-2024)\n\n" + md(v, "{:,.2f}").replace("| year |", "| series |"))
open(os.path.join(L.ROOT, "docs", "tables.md"), "w").write("\n\n".join(S) + "\n")
print("wrote docs/tables.md")
